"""Image generation from per-view control sequences, the camera tensor processors Cosmos builds on."""

from __future__ import annotations

import math
from collections.abc import Sequence
from typing import TYPE_CHECKING, Protocol

import torch
import warp as wp

from isaaclab.sim import SimulationContext
from isaaclab.utils import index_fill_, instantiate
from isaaclab.utils.tensor_processors import TensorProcessor
from isaaclab.utils.warp import ProxyArray

if TYPE_CHECKING:
    from .image_transfer_cfg import DepthControlProcessorCfg, ImageTransferProcessorCfg

_SEED_MODULUS = 2**31


class ImageTransferStream(Protocol):
    """One batched generation stream with temporal state for each camera view.

    Controls are uint8 THWC three-channel image sequences, one per view, valid until :meth:`step`
    returns: the processor reuses their storage for later captures, so a stream that keeps a chunk
    copies it. Returned images must be uint8 THWC sRGB with the same sequence lengths and image
    size. Calls run on the current Torch stream; returned tensors must be ready on that stream.
    Reset rows discard all episode state and start again from the given seeds; the first step names the views
    that reset before it.
    """

    def step(
        self,
        controls: list[torch.Tensor],
        reset_rows: tuple[int, ...],
        seeds: tuple[int, ...],
        episodes: tuple[int, ...] | None = None,
    ) -> list[torch.Tensor] | None:
        """Consume one chunk per view and return the corresponding images.

        Args:
            controls: One control chunk per view.
            reset_rows: Views starting a new episode, in increasing order.
            seeds: The seed of each view in ``reset_rows``.
            episodes: Episode number of each view in ``reset_rows``, counted from the stream's start, for streams
                that follow episodes ending between two steps. None counts one episode per reset.

        Returns:
            One image chunk per view, or None when a stream shared with other cameras publishes them later.
        """
        ...

    def close(self) -> None:
        """Release the stream's state. Repeated calls must be safe."""
        ...


class ImageTransferModel(Protocol):
    """Shared, stateless model resource constructed from a :class:`~isaaclab.sim.BackendCfg`.

    :meth:`~isaaclab.sim.SimulationContext.get_or_create_backend` returns one model for equal
    configurations, so the model must keep per-camera state in the streams it opens.
    """

    def open_stream(self, num_views: int, seeds: tuple[int, ...]) -> ImageTransferStream:
        """Open a stream for ``num_views`` camera views, seeded with one initial seed per view."""
        ...

    def close(self) -> None:
        """Release the model. Repeated calls must be safe."""
        ...


class ImageTransferProcessor(TensorProcessor):
    """Queue uint8 controls per view and publish images generated by an application-owned model.

    Cameras using this processor must render synchronously so repeated or delayed images do not advance history:
    a call without ``env_mask``, as an asynchronous camera makes, raises.

    Each call queues one control for every view in ``env_mask``. With
    ``update_period > 0``, environments that reset independently capture at different steps, so a capture can
    cover only some views; the others keep their last render, which is not a new frame. Views advance together:
    when every view starts an episode, the stream generates once each has ``initial_frames``; otherwise it
    generates once every continuing view has ``update_frames``. A view that reset meanwhile starts its new episode
    with its newest ``initial_frames`` and drops its older queued controls, so all views keep one chunk cadence.
    The output takes each view's last generated image and holds it until the next chunk; a reset view shows black
    until its episode starts.

    The queues and the per-view state stay on the camera's device, so captures and resets apply ``env_mask`` without
    waiting for the GPU. The host counts calls, which bounds how many controls each view can have, and reads the
    state only when every view may have its chunk: once per chunk when every capture covers every view.

    A stream error or invalid result marks the processor as failed: the stream may already have advanced,
    so it is never retried against the same queues. Recreate the camera or processor instead.
    """

    def __init__(self, cfg: ImageTransferProcessorCfg, data: dict[str, ProxyArray]):
        """Open a generation stream for the views of the control input.

        Args:
            cfg: Processor configuration. Its first input names the controls and its only output the images.
            data: Named input buffers; the controls have shape ``(N, H, W, 3)``.

        Raises:
            ValueError: If the control shape or the chunk settings are invalid.
        """
        super().__init__(cfg)
        controls = data[cfg.inputs[0]]
        data_dim = tuple(controls.shape)
        _validate(cfg, data_dim)
        self._data_dim = data_dim
        num_views = data_dim[0]
        sim = SimulationContext.instance()
        # The simulation owns shared models; a model built without one belongs to this processor.
        self._owned_model: ImageTransferModel | None = None
        if sim is not None:
            model = sim.get_or_create_backend(cfg.backend)
        else:
            model = self._owned_model = instantiate(cfg.backend)
        seeds = cfg.seed if isinstance(cfg.seed, (list, tuple)) else [cfg.seed + row for row in range(num_views)]
        self._seeds = tuple(seed % _SEED_MODULUS for seed in seeds)
        self._stream = model.open_stream(num_views, self._seeds)
        output = wp.zeros(data_dim, dtype=wp.uint8, device=controls.device)
        self._outputs = {cfg.outputs[0]: ProxyArray(output)}
        self._output = self._outputs[cfg.outputs[0]].torch
        device = self._output.device
        # Allocated at the first capture. Slot max_pending_frames is a spare that a full view writes, so a write
        # needs no host check.
        self._queue: torch.Tensor | None = None
        self._rows = torch.arange(num_views, device=device)
        self._all_views = torch.ones(num_views, dtype=torch.bool, device=device)
        self._selected = torch.zeros(num_views, dtype=torch.bool, device=device)
        self._counts = torch.zeros(num_views, dtype=torch.int64, device=device)
        self._fresh = torch.ones(num_views, dtype=torch.bool, device=device)
        self._overflow = torch.zeros(num_views, dtype=torch.bool, device=device)
        self._resets = torch.zeros(num_views, dtype=torch.bool, device=device)
        self._episodes = torch.zeros(num_views, dtype=torch.int64, device=device)
        # Captures each view needs, at least, before its chunk can be complete; exact after each host read.
        self._waits = [cfg.initial_frames] * num_views
        self._failed = False
        self._closed = False

    def __call__(self, data: dict[str, ProxyArray], env_mask: wp.array | None = None) -> dict[str, ProxyArray]:
        """Queue one control per captured view and generate a chunk when every view has one.

        Args:
            data: Named input buffers: the controls of shape ``(N, H, W, 3)``, dtype uint8.
            env_mask: Boolean mask of the views captured in this call.

        Returns:
            The latest generated images, shape ``(N, H, W, 3)``, under the output name. The buffer is reused by
            later calls.

        Raises:
            RuntimeError: If the processor is closed or failed, or a captured view's queue was full.
            ValueError: If ``env_mask`` is None, or the controls or the generated images have the wrong shape or
                type.
        """
        cfg = self._cfg
        frames = self._controls(data, env_mask)
        with torch.no_grad():
            if self._queue is None:
                shape = (self._data_dim[0], cfg.max_pending_frames + 1, *self._data_dim[1:])
                self._queue = torch.zeros(shape, dtype=torch.uint8, device=self._output.device)
            # Every view writes its next free slot, a full view the spare one; only captured views keep theirs.
            captured = self._select(None, env_mask)
            full = self._counts >= cfg.max_pending_frames
            self._queue[self._rows, self._counts] = frames
            self._overflow |= captured & full
            self._counts += captured & ~full
            # A call adds at most one control per view, so no chunk can be complete before every wait ends.
            self._waits = [max(wait - 1, 0) for wait in self._waits]
            if any(self._waits):
                return dict(self._outputs)
            state = (self._counts, self._fresh.long(), self._overflow.long(), self._resets.long(), self._episodes)
            counts, fresh, overflow, resets, episodes = torch.stack(state).tolist()
            if any(overflow):
                raise RuntimeError("Image transfer control queue is full; views must reset and advance compatibly.")
            chunk = [cfg.initial_frames if start else cfg.update_frames for start in fresh]
            self._waits = [max(size - count, 0) for size, count in zip(chunk, counts)]
            if any(self._waits):
                return dict(self._outputs)
            # A view starting while others continue joins at the next chunk with its newest controls.
            controls = [
                self._queue[row, count - size : count] if start else self._queue[row, :size]
                for row, (count, size, start) in enumerate(zip(counts, chunk, fresh))
            ]
            # Views that reset since the last chunk, also before the first one, start from their episode's seed.
            rows = tuple(row for row, reset in enumerate(resets) if reset)
            seeds = self._episode_seeds(rows, episodes)
            try:
                self._publish(self._stream.step(controls, rows, seeds), chunk)
            except Exception:
                self._failed = True
                raise
            # Continuing views keep the controls after their chunk; starting views drop their older ones.
            kept = [0 if start else count - size for count, size, start in zip(counts, chunk, fresh)]
            for row, (left, size) in enumerate(zip(kept, chunk)):
                if left:
                    self._queue[row, :left] = self._queue[row, size : size + left].clone()
            self._counts.copy_(torch.where(self._fresh, 0, self._counts - cfg.update_frames))
            self._fresh.zero_()
            self._resets.zero_()
            self._waits = [cfg.update_frames - left for left in kept]
        return dict(self._outputs)

    def _publish(self, generated: list[torch.Tensor], chunk: list[int]) -> None:
        """Publish each view's last generated image, once the whole result is validated.

        Args:
            generated: One uint8 THWC image chunk per view.
            chunk: Frames each view's chunk must hold.

        Raises:
            ValueError: If the images do not match the views; the processor is then failed.
        """
        if len(generated) != self._data_dim[0] or any(
            tuple(images.shape) != (size, *self._data_dim[1:]) or images.dtype != torch.uint8
            for images, size in zip(generated, chunk)
        ):
            self._failed = True
            raise ValueError("Image transfer must return uint8 THWC RGB matching each view's control chunk.")
        for row, images in enumerate(generated):
            self._output[row].copy_(images[-1])

    def reset(self, env_ids: Sequence[int] | torch.Tensor | None = None, env_mask: wp.array | None = None) -> None:
        """Discard the queued controls and episode state of the selected views.

        Every reset counts as an episode, also before the first generation, so episode seeds and prompts follow
        the environment's episodes from its start.

        Args:
            env_ids: Views to reset, as indices or a boolean mask. Defaults to None, which resets all views.
            env_mask: Boolean mask of the views to reset. Takes precedence over ``env_ids``. Defaults to None.
        """
        if self._closed:
            return
        self._reset_views(self._select(env_ids, env_mask))

    def _reset_views(self, selected: torch.Tensor) -> None:
        """Discard the queued controls and episode state of the views in the boolean mask ``selected``."""
        self._counts.masked_fill_(selected, 0)
        self._fresh |= selected
        self._overflow &= ~selected
        self._episodes += selected
        self._resets |= selected
        self._output.masked_fill_(selected.view(-1, 1, 1, 1), 0)
        # A reset view needs only its initial chunk; the host does not read which views reset.
        self._waits = [min(wait, self._cfg.initial_frames) for wait in self._waits]

    def close(self) -> None:
        """Close the stream and, without a simulation context, the model."""
        if self._closed:
            return
        self._closed = True
        self._queue = None
        try:
            self._stream.close()
        finally:
            if self._owned_model is not None:
                self._owned_model.close()

    def _select(self, env_ids: Sequence[int] | torch.Tensor | None, env_mask: wp.array | None) -> torch.Tensor:
        """Return the selected views as a boolean mask on the output's device, without reading it on the host.

        The result may be reused storage, so callers do not modify it.
        """
        if env_mask is not None:
            return wp.to_torch(env_mask).to(device=self._output.device, dtype=torch.bool)
        if env_ids is None:
            return self._all_views
        # Indices or a boolean mask, as the other tensor processors take them.
        self._selected.zero_()
        index_fill_(self._selected, env_ids, True)
        return self._selected

    def _controls(self, data: dict[str, ProxyArray], env_mask: wp.array | None) -> torch.Tensor:
        """Return a call's control images, checked against the shape the processor was built for.

        Raises:
            RuntimeError: If the processor is closed or failed.
            ValueError: If ``env_mask`` is None, or the controls have the wrong shape or type.
        """
        if self._closed or self._failed:
            raise RuntimeError("Image transfer processor is closed or failed; recreate it.")
        if env_mask is None:
            raise ValueError(
                "Image transfer requires an explicit env_mask; use synchronous rendering"
                " (renderer_cfg.async_rendering=False) for cameras."
            )
        frames = data[self._cfg.inputs[0]].torch
        if tuple(frames.shape) != self._data_dim or frames.dtype != torch.uint8:
            raise ValueError(f"Image transfer controls must be uint8 with shape {self._data_dim}.")
        return frames

    def _episode_seeds(self, rows: tuple[int, ...], episodes: list[int]) -> tuple[int, ...]:
        """Return the seeds of the views ``rows`` in their current episodes, given every view's episode number."""
        num_views = self._data_dim[0]
        return tuple((self._seeds[row] + episodes[row] * num_views) % _SEED_MODULUS for row in rows)


class DepthControlProcessor(TensorProcessor):
    """Publish uint8 three-channel controls from the camera's metric depth; see :func:`depth_to_control`."""

    def __init__(self, cfg: DepthControlProcessorCfg, data: dict[str, ProxyArray]):
        """Allocate the controls for the views of the depth input.

        Args:
            cfg: Processor configuration with the depth input, the control output and the depth range.
            data: Named input buffers; the depth has shape ``(N, H, W, 1)``.
        """
        super().__init__(cfg)
        depth = data[cfg.inputs[0]]
        output = wp.zeros((*depth.shape[:-1], 3), dtype=wp.uint8, device=depth.device)
        self._outputs = {cfg.outputs[0]: ProxyArray(output)}
        self._output = self._outputs[cfg.outputs[0]].torch

    def __call__(self, data: dict[str, ProxyArray], env_mask: wp.array | None = None) -> dict[str, ProxyArray]:
        """Convert the depth of every view and return the controls under the output name."""
        cfg = self._cfg
        with torch.no_grad():
            self._output.copy_(depth_to_control(data[cfg.inputs[0]].torch, near=cfg.near, far=cfg.far))
        return dict(self._outputs)


def depth_to_control(data: torch.Tensor, near: float, far: float) -> torch.Tensor:
    """Map metric depth to uint8 three-channel controls.

    Hits at ``near`` become white and hits at ``far`` black. Missing, nonfinite, and nonpositive
    depth becomes black.

    Args:
        data: Depth [m] of shape ``(N, H, W, 1)``.
        near: White depth endpoint [m].
        far: Black depth endpoint [m].

    Returns:
        Controls of shape ``(N, H, W, 3)``, dtype uint8.
    """
    if not (math.isfinite(near) and math.isfinite(far) and 0 < near < far):
        raise ValueError("Depth bounds must be finite and satisfy 0 < near < far.")
    valid = torch.isfinite(data) & (data > 0)
    metric = torch.where(valid, data, far)
    pixels = ((far - metric) / (far - near)).clamp(0, 1).mul(255).round().to(torch.uint8)
    return pixels.expand(*pixels.shape[:-1], 3)


def _validate(cfg: ImageTransferProcessorCfg, data_dim: tuple[int, ...]) -> None:
    if len(data_dim) != 4 or data_dim[-1] != 3:
        raise ValueError(f"Image transfer expects controls with shape (N, H, W, 3), got {data_dim}.")
    sizes = (cfg.initial_frames, cfg.update_frames, cfg.max_pending_frames)
    if any(type(value) is not int or value < 1 for value in sizes):
        raise ValueError("Chunk sizes and queue capacity must be positive integers.")
    if cfg.max_pending_frames < max(cfg.initial_frames, cfg.update_frames):
        raise ValueError("Queue capacity must accommodate both configured chunk sizes.")
    seeds = cfg.seed if isinstance(cfg.seed, (list, tuple)) else [cfg.seed]
    if any(type(seed) is not int for seed in seeds):
        raise ValueError("Image transfer seeds must be integers.")
    if isinstance(cfg.seed, (list, tuple)) and len(cfg.seed) != data_dim[0]:
        raise ValueError(f"A seed list needs one seed per view: {len(cfg.seed)} seeds for {data_dim[0]} views.")
