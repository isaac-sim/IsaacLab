"""Build ``sandbox_particles.usdc``: a small work tray cut out of ~/Documents/sand.usd.

WHY: sand.usd holds 930k sand + 116k gravel PhysX PBD particles in a 6.2 m container. Isaac Lab clones the
scene once per environment, so even 16 envs would be ~17 M particles. This script keeps only the particles
inside a work tray, adds a matching rigid floor + 4 walls to hold them in, and writes the result as a USD
layer that still *references* sand.usd for the particle systems, the PBD material and the rigid materials,
so your sand/gravel physics settings are used unchanged.

Layout (file coordinates of sand.usd; sand.usd is never modified):
    gravel zone  x 5.5 .. 8.25   (sits on a 1 cm riser)
    sand   zone  x 8.25 .. 11.5
The default tray is centred on the gravel/sand boundary (x = 8.25) so both materials are in reach.

Usage (from the IsaacLab repo root):
    uv run python source/isaaclab_tasks/isaaclab_tasks/core/bag_lift/assets/build_sandbox_particles.py
    # smaller / larger tray:   --x-half 0.25 --y-min -0.10 --y-max 0.25
    # fast variant without particles (static colored sand/gravel slabs), writes sandbox_tray.usdc:
    uv run python source/isaaclab_tasks/isaaclab_tasks/core/bag_lift/assets/build_sandbox_particles.py --no-particles

The *current* fast tray used by the task is the hand-authored assets/sandbox_tray.usda (no sand.usd
reference). Re-run this script only when you want particles or the colored-slab usdc back.

If you change --center-x or the floor height, keep SANDBOX_WORK_CENTER_X / SANDBOX_FLOOR_Z in
bag_sand_scene.py in sync (the defaults here match them).

HOW TO EDIT
    SRC / TERRAIN     path into your sand.usd (only this file is read; sand.usd is never modified)
    FLOOR_TOP         z of the container floor in sand.usd
    --x-half etc.     tray size; smaller = fewer particles = faster
    box()             rigid floor/walls; pad=0.25 so the arm base also stands on the floor
"""

import argparse
from pathlib import Path

import numpy as np

from pxr import Gf, Sdf, Usd, UsdGeom, UsdPhysics, UsdShade, Vt

SRC = "/home/joshua/Documents/sand.usd"
TERRAIN = Sdf.Path("/World/ground/terrain")
FLOOR_TOP = 0.4108  # z of the container floor surface in the file
GRAVEL_RISER = 0.0100  # gravel sits on a 1 cm riser in the file; the tray floor is flat, so gravel is lowered by this


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--center-x", type=float, default=8.25, help="tray centre in file x [m] (8.25 = gravel/sand boundary)"
    )
    ap.add_argument("--x-half", type=float, default=0.30, help="tray half length in x [m]")
    ap.add_argument("--y-min", type=float, default=-0.12, help="tray edge toward the arm [m] (env-frame y)")
    ap.add_argument("--y-max", type=float, default=0.30, help="tray far edge [m] (env-frame y)")
    ap.add_argument("--wall-height", type=float, default=0.06)
    ap.add_argument(
        "--no-particles",
        action="store_true",
        help="fast variant: no PBD particles; the sand/gravel layer is two static colored slabs instead",
    )
    ap.add_argument("--layer-height", type=float, default=0.030, help="--no-particles: slab height above the floor [m]")
    ap.add_argument(
        "--out", default=None, help="default: sandbox_particles.usdc, or sandbox_tray.usdc with --no-particles"
    )
    args = ap.parse_args()
    if args.out is None:
        name = "sandbox_tray.usdc" if args.no_particles else "sandbox_particles.usdc"
        args.out = str(Path(__file__).parent / name)

    cx, xh, y0, y1 = args.center_x, args.x_half, args.y_min, args.y_max
    src = Usd.Stage.Open(SRC)

    out = Usd.Stage.CreateNew(args.out)
    UsdGeom.SetStageUpAxis(out, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(out, 1.0)
    root = out.DefinePrim("/Sandbox", "Xform")
    out.SetDefaultPrim(root)
    root.GetReferences().AddReference(SRC, TERRAIN)
    out.GetRootLayer().documentation = (
        "Generated by build_sandbox_particles.py -- do not edit by hand, re-run the script instead."
    )

    # 1. switch off the original (6.2 m) rigid container and the full particle clouds
    for name in (
        "floor",
        "left_wall",
        "right_wall",
        "entry_wall",
        "exit_wall",
        "gravel_floor_riser",
        "granular_container",
        "gravel_particles",
        "sand_particles",
    ):
        out.OverridePrim(f"/Sandbox/{name}").SetActive(False)

    if args.no_particles:
        # the particle systems and their material are not needed either (and cannot be cloned by PhysX)
        for name in ("gravel_ParticleSystem", "sand_ParticleSystem", "PBDMaterial"):
            out.OverridePrim(f"/Sandbox/{name}").SetActive(False)

    # 2. cropped particle clouds
    kept = {}
    crops = (("sand_crop", "sand_particles", 0.0), ("gravel_crop", "gravel_particles", -GRAVEL_RISER))
    for name, src_name, z_shift in () if args.no_particles else crops:
        sp = src.GetPrimAtPath(TERRAIN.AppendChild(src_name))
        pts = np.array(sp.GetAttribute("points").Get(), dtype=np.float64)
        keep = (np.abs(pts[:, 0] - cx) <= xh) & (pts[:, 1] >= y0) & (pts[:, 1] <= y1)
        dst_path = Sdf.Path(f"/Sandbox/{name}")
        pts_new = pts[keep]
        pts_new[:, 2] += z_shift
        vel = np.array(sp.GetAttribute("velocities").Get())[keep]
        wid = np.array(sp.GetAttribute("widths").Get())[keep]
        col = np.array(sp.GetAttribute("primvars:displayColor").Get())[keep]

        points = UsdGeom.Points.Define(out, dst_path)
        points.GetPointsAttr().Set(Vt.Vec3fArray.FromNumpy(pts_new.astype(np.float32)))
        points.GetVelocitiesAttr().Set(Vt.Vec3fArray.FromNumpy(vel.astype(np.float32)))
        points.GetWidthsAttr().Set(Vt.FloatArray.FromNumpy(wid.astype(np.float32)))
        points.GetDisplayColorPrimvar().Set(Vt.Vec3fArray.FromNumpy(col.astype(np.float32)))
        points.GetDisplayColorPrimvar().SetInterpolation(UsdGeom.Tokens.vertex)
        dp = points.GetPrim()
        # copy the particle-set settings (fluid / particleGroup / selfCollision) as authored in sand.usd
        for a in sp.GetAttributes():
            if a.GetName().startswith("physxParticle:") and a.HasValue():
                dp.CreateAttribute(a.GetName(), a.GetTypeName()).Set(a.Get())
        # PhysX wants the total mass of the particle set; scale it with the particle count
        UsdPhysics.MassAPI.Apply(dp).CreateMassAttr(
            float(sp.GetAttribute("physics:mass").Get()) * keep.sum() / len(pts)
        )
        # re-target the relationships (they point at the original absolute paths inside sand.usd)
        for rel in sp.GetRelationships():
            tg = [Sdf.Path(str(t).replace(str(TERRAIN), "/Sandbox")) for t in rel.GetTargets()]
            if tg and rel.GetName() in ("physxParticle:particleSystem", "material:binding"):
                dp.CreateRelationship(rel.GetName()).SetTargets(tg)
        kept[name] = (int(keep.sum()), len(pts))

    # 3. rigid tray: floor + 4 walls, using the original container's rigid material (friction 0.6)
    mat_path = Sdf.Path("/Sandbox/RigidMaterials/granular_container")

    def box(name: str, center: tuple, size: tuple, color: tuple | None = None):
        cube = UsdGeom.Cube.Define(out, f"/Sandbox/{name}")
        cube.GetSizeAttr().Set(1.0)
        xf = UsdGeom.Xformable(cube)
        xf.AddTranslateOp().Set(Gf.Vec3d(*center))
        xf.AddScaleOp().Set(Gf.Vec3f(*size))
        cube.GetPurposeAttr().Set(UsdGeom.Tokens.default_)
        if color is not None:
            cube.GetDisplayColorAttr().Set(Vt.Vec3fArray([Gf.Vec3f(*color)]))
        prim = cube.GetPrim()
        UsdPhysics.CollisionAPI.Apply(prim)
        UsdShade.MaterialBindingAPI.Apply(prim).Bind(
            UsdShade.Material(out.GetPrimAtPath(mat_path)), UsdShade.Tokens.weakerThanDescendants, "physics"
        )

    pad = 0.25  # floor extends beyond the walls so the arm base also stands on it
    fx0, fx1, fy0, fy1 = cx - xh - pad, cx + xh + pad, y0 - pad, y1 + pad
    t = 0.01
    box("TrayFloor", ((fx0 + fx1) / 2, (fy0 + fy1) / 2, FLOOR_TOP - 0.05), (fx1 - fx0, fy1 - fy0, 0.10))
    wz = FLOOR_TOP + args.wall_height / 2
    box("TrayWallN", (cx, y1 + t / 2, wz), (2 * xh + 2 * t, t, args.wall_height))
    box("TrayWallS", (cx, y0 - t / 2, wz), (2 * xh + 2 * t, t, args.wall_height))
    box("TrayWallW", (cx - xh - t / 2, (y0 + y1) / 2, wz), (t, y1 - y0, args.wall_height))
    box("TrayWallE", (cx + xh + t / 2, (y0 + y1) / 2, wz), (t, y1 - y0, args.wall_height))

    if args.no_particles:
        # static stand-ins for the sand / gravel bed (same surface height the particles settle at)
        h = args.layer_height
        zc = FLOOR_TOP + h / 2
        box("GravelLayer", (cx - xh / 2, (y0 + y1) / 2, zc), (xh, y1 - y0, h), color=(0.40, 0.40, 0.40))
        box("SandLayer", (cx + xh / 2, (y0 + y1) / 2, zc), (xh, y1 - y0, h), color=(0.76, 0.65, 0.42))

    out.GetRootLayer().Save()
    print(f"wrote {args.out}")
    for k, (n, tot) in kept.items():
        print(f"  {k}: kept {n} of {tot} particles")


if __name__ == "__main__":
    main()
