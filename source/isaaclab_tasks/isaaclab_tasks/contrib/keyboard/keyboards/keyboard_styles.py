def sample_style(name: str | None, family: str, rng: random.Random) -> KeyboardStyle:
    """Sample a coherent keyboard style for a layout family."""

    styles = style_archetypes(rng)
    if name is not None:
        return styles[name]
    compatible = COMPATIBLE_STYLES_BY_FAMILY[family]
    return styles[rng.choice(compatible)]


