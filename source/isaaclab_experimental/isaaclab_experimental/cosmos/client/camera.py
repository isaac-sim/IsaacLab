logger = logging.getLogger(__name__)

COSMOS_CANVASES = tuple(CANVAS_ASPECT_RATIOS)
"""Image sizes ``(height, width)`` the Cosmos service accepts."""

COSMOS_OPTIONS = ("prompt", "camera", "control", "near", "far", "endpoint", "transport")
"""Options a Cosmos config file may set; each is an argument of :func:`apply_cosmos`."""


def read_cosmos_config(path: str) -> dict[str, Any]:
    """Read the Cosmos options of a task from a YAML file.

    Args:
        path: YAML file mapping option names (:data:`COSMOS_OPTIONS`) to values, for example
            ``prompt: A kitchen.`` or ``endpoint: unix:///tmp/cosmos.sock``. Omitted options keep their defaults.

    Returns:
        The options, to pass to :func:`apply_cosmos`.

    Raises:
        ValueError: If the file is not a mapping or sets an option that does not exist.
    """
    options = load_yaml(path) or {}
    if not isinstance(options, dict):
        raise ValueError(f"The Cosmos config {path} must map option names to values.")
    unknown = sorted(set(options) - set(COSMOS_OPTIONS))
    if unknown:
        raise ValueError(f"Unknown Cosmos option(s) {unknown} in {path}; the options are {list(COSMOS_OPTIONS)}.")
    return options


def cosmos_camera(
    camera: CameraCfg,
    model: CosmosModelCfg,
    *,
    near: float = 0.1,
    far: float = 2.0,
    edge_thresholds: tuple[int, int] = (100, 200),
    canvas: tuple[int, int] | None = None,
) -> CameraCfg:
    """Return a copy of ``camera`` whose ``rgb`` output is generated by Cosmos at the camera's size.

    The copy renders the control input at a Cosmos canvas, by default the one closest to the camera's aspect ratio,
    widening the lens aperture so the camera's original view is the canvas's center crop. Its chain prepares controls
    with :func:`depth_processor` or :func:`edge_processor` (``model.modality``), generates with Cosmos, and scales the
    result back to the camera's width and height. Observation terms that read ``rgb`` keep their image shape; the
    camera's ``image_shape`` and intrinsics describe the canvas.

    Args:
        camera: Pinhole camera publishing only ``rgb``, for example a task's policy camera.
        model: Cosmos service connection, prompt and control type (``"depth"`` or ``"edge"``).
        near: Depth rendered white [m], for depth control.
        far: Depth rendered black [m], for depth control.
        edge_thresholds: Lower and upper Canny thresholds, for edge control.
        canvas: Cosmos canvas ``(height, width)`` from :data:`COSMOS_CANVASES`. Defaults to None, which selects the
            canvas closest to the camera's aspect ratio. Cameras sharing a session need one canvas.

    Returns:
        The Cosmos camera configuration.

    Raises:
        ValueError: If the camera publishes outputs other than ``rgb``, already has modifiers, uses a fisheye lens,
            or the control type or canvas is unsupported.
    """
    if model.modality not in ("depth", "edge"):
        raise ValueError(f"Cosmos cameras support depth or edge control, got {model.modality!r}.")
    if list(camera.data_types) != ["rgb"]:
        raise ValueError(
            f"A Cosmos camera publishes only 'rgb'; this camera requests {camera.data_types}. "
            "Use a camera that observes rgb only."
        )
    if camera.modifiers:
        raise ValueError("The camera already has modifiers; Cosmos replaces its rgb output.")
    if canvas is not None and tuple(canvas) not in COSMOS_CANVASES:
        raise ValueError(f"Cosmos canvases are {list(COSMOS_CANVASES)}, got {canvas}.")
    canvas_height, canvas_width = tuple(canvas) if canvas is not None else _closest_canvas(camera)
    if model.modality == "depth":
        input_name, chain = depth_processor(model, near=near, far=far)
    else:
        input_name, chain = edge_processor(model, lower=edge_thresholds[0], upper=edge_thresholds[1])
    if (camera.height, camera.width) != (canvas_height, canvas_width):
        chain.append(ModifierCfg(func=center_crop_resize, params={"width": camera.width, "height": camera.height}))
    return replace(
        camera,
        width=canvas_width,
        height=canvas_height,
        spawn=_canvas_spawn(camera, canvas_height, canvas_width),
        modifiers={input_name: chain},
    )


def service_capabilities(
    endpoint: str = DEFAULT_ENDPOINT, timeout: float = 5.0, *, require_idle: bool = False
) -> dict[str, Any]:
    """Return the running Cosmos service's capabilities, such as its independent reset support.

    Args:
        endpoint: Cosmos service endpoint.
        timeout: Connection and response timeout [s].
        require_idle: Reject a busy service before configuring a new camera session.

    Returns:
        The capabilities reported by ``isaaclab cosmos status``.

    Raises:
        RuntimeError: If the service is unavailable, or busy when require_idle is True.
    """
    try:
        reply, _ = request(endpoint, {"op": "status"}, timeout=timeout)
    except OSError as error:
        raise RuntimeError(
            f"Cosmos service at {endpoint} is unavailable or still starting; wait for its ready message, "
            "or start isaaclab-cosmos-server as described in cosmos_service.md."
        ) from error
    if require_idle and reply.get("session_active", False):
        raise RuntimeError(
            f"Cosmos service at {endpoint} already has an active camera session; close the other training/play "
            "process or choose another service with the Cosmos config option `endpoint`."
        )
    return reply["capabilities"]


def apply_cosmos(
    env_cfg: Any,
    *,
    prompt: str | list[str] | None = None,
    camera: str | Sequence[str] | None = None,
    control: Literal["depth", "edge"] | None = None,
    near: float | None = None,
    far: float | None = None,
    endpoint: str | list[str] | None = None,
    transport: Literal["auto", "cuda_ipc", "socket"] | None = None,
    num_envs: int | None = None,
) -> None:
    """Put Cosmos on a task's camera in place.

    Selects the scene camera publishing only ``rgb`` (or ``camera``) and replaces it with :func:`cosmos_camera`. It
    sets the environment count, whose cameras each service generates as one batch, and derives the episode budget
    without changing capture timing. It checks that every service is running and idle. For an existing Cosmos camera,
    it updates settings without rebuilding its modifier chain. Tasks must read the camera image from its output;
    Direct tasks that size their observation space from the camera configuration are not supported, because the
    camera renders at the Cosmos canvas.

    Several cameras share one session: each capture generates all their environments as one batch, camera ``k``'s
    environment ``v`` being view ``k * num_envs + v`` (see :attr:`CosmosModelCfg.cameras`). They render at the canvas
    closest to the first camera's aspect ratio, each keeping its own output size, and need the same update period.

    Args:
        env_cfg: Task environment configuration.
        prompt: Appearance prompt, or a list: cycled per episode for one environment, one per view for several
            environments or cameras (see :attr:`CosmosModelCfg.prompt`). None preserves an existing camera's prompt.
        camera: Scene camera name, a list of names whose cameras share one session, or ``"all"`` for every camera
            publishing ``rgb``. Defaults to None, which selects the only rgb camera.
        control: Control type: ``"depth"`` or ``"edge"``. None preserves a preset or uses depth.
            An existing preset's control type cannot be changed here.
        near: Depth rendered white [m]. None preserves a preset or uses 0.1.
        far: Depth rendered black [m]. None preserves a preset or uses 2.0.
        endpoint: Cosmos service endpoint, or a list of services, for example one per GPU, that split the
            environments into contiguous shares. None preserves a preset or uses the default endpoint.
        transport: How images move to and from the service. None preserves a preset or uses auto.
        num_envs: Environments to generate together. Defaults to None, which uses one. Each session requests its
            share from its service. A service with several needs compiled inference with per-view caches for
            independent resets, and enough GPU memory for its batch.

    Raises:
        ValueError: If no single rgb camera can be selected, a selected entity is not a suitable camera, sensors
            update eagerly, a camera renders asynchronously, cameras sharing a session have modifiers already or
            different update periods, there are fewer views than services, or a service cannot batch its share.
        RuntimeError: If a service is not running or already has a camera session.
    """
    num_envs = 1 if num_envs is None else num_envs
    if type(num_envs) is not int or num_envs < 1:
        raise ValueError(f"Cosmos needs a positive number of environments, got {num_envs!r}.")
    names = _camera_names(env_cfg.scene, camera)
    camera_cfgs = [getattr(env_cfg.scene, name, None) for name in names]
    for name, camera_cfg in zip(names, camera_cfgs):
        if not isinstance(camera_cfg, CameraCfg):
            raise ValueError(f"Scene entity {name!r} is not a camera.")
    if len(names) > 1:
        if any(camera_cfg.modifiers for camera_cfg in camera_cfgs):
            raise ValueError(
                "Cameras sharing a Cosmos session must not have modifiers yet; select ordinary rgb cameras."
            )
        if len({camera_cfg.update_period for camera_cfg in camera_cfgs}) > 1:
            raise ValueError("Cameras sharing a Cosmos session need the same update_period, so they capture together.")
    camera_cfg = camera_cfgs[0]
    transfers = [
        item for chain in camera_cfg.modifiers.values() for item in chain if isinstance(item, CosmosTransferModifierCfg)
    ]
    if len(transfers) > 1:
        raise ValueError("The selected camera has several Cosmos modifiers; configure their settings explicitly.")
    existing = transfers[0].backend if transfers else None
    if existing is not None and control is not None and control != existing.modality:
        raise ValueError(
            f"This Cosmos preset prepares {existing.modality} controls; omit the Cosmos config option `control` "
            "or select an ordinary RGB camera task with --cosmos to use another control."
        )
    control = control or (existing.modality if existing is not None else "depth")
    endpoint = endpoint or (existing.endpoint if existing is not None else DEFAULT_ENDPOINT)
    transport = transport or (existing.transport if existing is not None else "auto")
    prompt = existing.prompt if prompt is None and existing is not None else prompt
    if control != "depth" and (near is not None or far is not None):
        raise ValueError("The Cosmos options `near` and `far` apply only to depth control.")
    endpoints = service_endpoints(endpoint)
    endpoint = endpoints[0] if len(endpoints) == 1 else endpoints
    shares = split_views(num_envs * len(names), len(endpoints))
    for address, share in zip(endpoints, shares):
        capabilities = service_capabilities(address, require_idle=True)
        # Views of one environment reset together, which the eager runtime supports.
        if num_envs > 1 and len(share) > 1 and not capabilities.get("partial_resets", False):
            raise ValueError(
                "Several Cosmos environments need a Framework runtime with per-view caches and compiled inference "
                f"for independent resets; start isaaclab-cosmos-server at {address} without --no-compile."
            )
    if prompt is None:
        logger.warning("Cosmos runs without a prompt; set `prompt` in the Cosmos config to describe the scene.")
    if env_cfg.scene.num_envs != num_envs:
        logger.info("Cosmos generates %d environment(s); the task default was %d.", num_envs, env_cfg.scene.num_envs)
        env_cfg.scene.num_envs = num_envs
    if not env_cfg.scene.lazy_sensor_update:
        raise ValueError("Cosmos needs scene.lazy_sensor_update=True so each image matches its simulation state.")
    if getattr(camera_cfg.renderer_cfg, "async_rendering", False):
        raise ValueError(
            "Cosmos needs synchronous rendering; set the camera's renderer_cfg.async_rendering=False "
            "(for a task's scene camera on the command line: env.scene.<camera>.renderer_cfg.async_rendering=False)."
        )
    if existing is None and hasattr(env_cfg, "observation_space") and not hasattr(env_cfg, "observations"):
        logger.warning(
            "Direct tasks that size their observation space from the camera configuration do not support --cosmos; "
            "the camera renders at the Cosmos canvas."
        )

    # Count actual captures at the sensor's existing cadence.
    steps_per_capture, _, budget = episode_frame_budget(env_cfg, camera_cfg.update_period)
    model = replace(
        existing or CosmosModelCfg(),
        endpoint=endpoint,
        prompt=prompt,
        modality=control,
        max_episode_frames=budget,
        transport=transport,
        cameras=tuple(names) if len(names) > 1 else (),
    )
    if existing is None:
        # Cameras sharing a session render at one canvas; each keeps its own output size.
        canvas = _closest_canvas(camera_cfg) if len(names) > 1 else None
        near, far = 0.1 if near is None else near, 2.0 if far is None else far
        for name, cfg in zip(names, camera_cfgs):
            setattr(env_cfg.scene, name, cosmos_camera(cfg, model, near=near, far=far, canvas=canvas))
    else:
        modifiers = {}
        for input_name, chain in camera_cfg.modifiers.items():
            updated = []
            for item in chain:
                if isinstance(item, CosmosTransferModifierCfg):
                    item = replace(item, backend=model)
                elif item.func is depth_to_control and (near is not None or far is not None):
                    params = dict(item.params)
                    params.update({key: value for key, value in (("near", near), ("far", far)) if value is not None})
                    if not (
                        math.isfinite(params["near"])
                        and math.isfinite(params["far"])
                        and 0 <= params["near"] < params["far"]
                    ):
                        raise ValueError("Cosmos depth bounds must be finite and satisfy 0 <= near < far.")
                    item = replace(item, params=params)
                updated.append(item)
            modifiers[input_name] = updated
        setattr(env_cfg.scene, names[0], replace(camera_cfg, modifiers=modifiers))
    capture_hz = 1 / (steps_per_capture * env_cfg.sim.dt * env_cfg.decimation)
    logger.info(
        "Cosmos camera %s: %d environment(s), %d-frame budget, %.3f captures/s, %.3f generated updates/s "
        "after the initial frame (simulation time).",
        ", ".join(names),
        num_envs,
        budget,
        capture_hz,
        capture_hz / 4,
    )
    if len(names) > 1:
        logger.info(
            "Cosmos cameras %s share one session of %d views: camera k's environment v is view k * %d + v.",
            ", ".join(names),
            num_envs * len(names),
            num_envs,
        )
    if len(endpoints) > 1:
        logger.info(
            "Cosmos splits the views across %d services: %s.",
            len(endpoints),
            ", ".join(f"{share.start}-{share.stop - 1} on {address}" for address, share in zip(endpoints, shares)),
        )
    if isinstance(prompt, (list, tuple)):
        logger.info(
            "Cosmos prompt list: %s.",
            "cycles across episodes" if num_envs * len(names) == 1 else "assigned per view and kept across resets",
        )


def _camera_names(scene: Any, camera: str | Sequence[str] | None) -> list[str]:
    """Return the selected cameras: the only rgb camera, the named ones, or every camera publishing rgb for "all"."""
    if camera is None:
        return [_select_camera(scene)]
    names = [camera] if isinstance(camera, str) else list(camera)
    if names == ["all"]:
        # Cameras publishing rgb with other outputs are kept, so cosmos_camera rejects them by name.
        names = _rgb_cameras(scene, only_rgb=False)
        if not names:
            raise ValueError("This scene has no camera publishing rgb for Cosmos.")
    elif not names or "all" in names or len(set(names)) != len(names):
        raise ValueError('Select Cosmos cameras by distinct scene names, or with "all" alone.')
    return names


def _rgb_cameras(scene: Any, *, only_rgb: bool) -> list[str]:
    """Return the scene's cameras publishing rgb, or only rgb, in declaration order."""
    names = []
    if is_dataclass(scene):
        for field in fields(scene):
            value = getattr(scene, field.name)
            if isinstance(value, CameraCfg) and (
                list(value.data_types) == ["rgb"] if only_rgb else "rgb" in value.data_types
            ):
                names.append(field.name)
    return names


def _select_camera(scene: Any) -> str:
    """Return the name of the scene's only camera that publishes only rgb."""
    names = _rgb_cameras(scene, only_rgb=True)
    if len(names) != 1:
        raise ValueError(
            f"Choose the Cosmos camera with the Cosmos config option `camera`; rgb cameras in this scene: {names}."
        )
    return names[0]


def _closest_canvas(camera: CameraCfg) -> tuple[int, int]:
    """Return the Cosmos canvas whose aspect ratio is closest to the camera's."""
    return min(COSMOS_CANVASES, key=lambda size: abs(math.log(size[1] / size[0] * camera.height / camera.width)))


def _canvas_spawn(camera: CameraCfg, canvas_height: int, canvas_width: int) -> Any:
    """Widen the pinhole aperture so the camera's original view is the canvas's center crop."""
    spawn = camera.spawn
    if isinstance(spawn, FisheyeCameraCfg):
        raise ValueError("Cosmos cameras need a pinhole lens; a fisheye view is not a center crop of a wider view.")
    if spawn is None:
        if canvas_width * camera.height != canvas_height * camera.width:
            logger.warning("The Cosmos canvas changes this camera's aspect ratio; its view is cropped.")
        return spawn
    # Renderers use square pixels, so the vertical aperture follows the horizontal one and the image size.
    vertical = spawn.horizontal_aperture * camera.height / camera.width
    if canvas_width * vertical >= canvas_height * spawn.horizontal_aperture:
        return replace(spawn, horizontal_aperture=vertical * canvas_width / canvas_height, vertical_aperture=vertical)
    return replace(spawn, vertical_aperture=spawn.horizontal_aperture * canvas_height / canvas_width)
