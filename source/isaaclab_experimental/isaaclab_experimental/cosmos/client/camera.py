"""Cosmos on compatible Isaac Lab cameras: :func:`cosmos_camera`."""

from __future__ import annotations

import logging
import math
from collections.abc import Sequence
from typing import Any

import torch

from isaaclab.sensors import CameraCfg
from isaaclab.sim import FisheyeCameraCfg
from isaaclab.utils import replace
from isaaclab.utils.tensor_processors import TensorProcessorCfg

from isaaclab_experimental.image_transfer import FunctionProcessorCfg

from .._protocol import CANVAS_ASPECT_RATIOS
from .control_profiles import DEPTH_FAR, DEPTH_NEAR, depth_processor
from .cosmos_model_cfg import CosmosModelCfg
from .cosmos_processor_cfg import CosmosTransferProcessorCfg

logger = logging.getLogger(__name__)

COSMOS_CANVASES = tuple(CANVAS_ASPECT_RATIOS)
"""Image sizes ``(height, width)`` the Cosmos service accepts."""


def cosmos_camera(
    camera: CameraCfg,
    model: CosmosModelCfg,
    *,
    control: Sequence[TensorProcessorCfg] | None = None,
    near: float = DEPTH_NEAR,
    far: float = DEPTH_FAR,
    canvas: tuple[int, int] | None = None,
    name: str = "",
) -> CameraCfg:
    """Return a copy of ``camera`` whose ``rgb`` output is generated by Cosmos at the camera's size.

    The copy renders the control input at a Cosmos canvas, by default the one closest to the camera's aspect ratio,
    widening the lens aperture so the camera's original view is the canvas's center crop. Its tensor processors
    prepare the control, generate with Cosmos, and scale the result back to the camera's width and height. The
    control is depth unless ``control`` gives other processors; the checkpoint accepts depth, segmentation, edge
    and blur controls, one kind per session, and the service is not told which kind it receives.

    Observation terms that read ``rgb`` keep their image shape; the camera's ``image_shape`` and intrinsics describe
    the canvas. The copy drops the camera's ``isp_cfg``, which processes the rendered image that Cosmos replaces.

    Args:
        camera: Pinhole camera publishing only ``rgb``, for example a task's policy camera.
        model: Cosmos service connection and prompt.
        control: Processors that write the ``control`` buffer from the camera's render outputs: uint8 images of
            shape (N, H, W, 3) at the canvas size, for example a
            :class:`~isaaclab_experimental.image_transfer.FunctionProcessorCfg` reading ``semantic_segmentation``
            or the rendered ``rgb``. Defaults to None, which uses the depth control of :func:`depth_processor`.
        near: Depth rendered white [m], for the default depth control.
        far: Depth rendered black [m], for the default depth control.
        canvas: Cosmos canvas ``(height, width)`` from the service's supported canvases. Defaults to None, which
            selects the canvas closest to the camera's aspect ratio. Cameras sharing a session need one canvas.
        name: Scene name of the camera, one of :attr:`CosmosModelCfg.cameras` when cameras share a session.

    Returns:
        The Cosmos camera configuration.

    Raises:
        ValueError: If the camera publishes outputs other than ``rgb``, already has tensor processors, uses a
            fisheye lens, the canvas is unsupported, or ``control`` writes no ``control`` buffer.
    """
    if list(camera.data_types) != ["rgb"]:
        raise ValueError(
            f"A Cosmos camera publishes only 'rgb'; this camera requests {camera.data_types}. "
            "Use a camera that observes rgb only."
        )
    if camera.tensor_processors:
        raise ValueError("The camera already has tensor processors; Cosmos replaces its rgb output.")
    if canvas is not None and tuple(canvas) not in COSMOS_CANVASES:
        raise ValueError(f"Cosmos canvases are {list(COSMOS_CANVASES)}, got {canvas}.")
    canvas_height, canvas_width = tuple(canvas) if canvas is not None else _closest_canvas(camera)
    if control is None:
        processors = depth_processor(model, near=near, far=far, camera=name)
    else:
        transfer = CosmosTransferProcessorCfg(backend=model, camera=name)
        if not any(transfer.inputs[0] in cfg.outputs for cfg in control):
            raise ValueError(f"The control processors must write the {transfer.inputs[0]!r} buffer Cosmos reads.")
        processors = [*control, transfer]
    if (camera.height, camera.width) != (canvas_height, canvas_width):
        processors.append(
            FunctionProcessorCfg(
                function=_center_crop_resize,
                params={"width": camera.width, "height": camera.height},
                inputs=["rgb"],
                outputs=["rgb"],
            )
        )
    return replace(
        camera,
        width=canvas_width,
        height=canvas_height,
        spawn=_canvas_spawn(camera, canvas_height, canvas_width),
        tensor_processors=processors,
        # An ISP processes the rendered image, which Cosmos replaces; the camera no longer renders it.
        isp_cfg=None,
    )


def _closest_canvas(camera: CameraCfg) -> tuple[int, int]:
    """Return the Cosmos canvas whose aspect ratio is closest to the camera's."""
    return min(COSMOS_CANVASES, key=lambda size: abs(math.log(size[1] / size[0] * camera.height / camera.width)))


def _canvas_spawn(camera: CameraCfg, canvas_height: int, canvas_width: int) -> Any:
    """Widen the pinhole aperture so the camera's original view is the canvas's center crop."""
    spawn = camera.spawn
    if isinstance(spawn, FisheyeCameraCfg):
        raise ValueError("Cosmos cameras need a pinhole lens; a fisheye view is not a center crop of a wider view.")
    if getattr(spawn, "distortion", None) is not None:
        # Calibrated intrinsics take precedence over the aperture, so a wider aperture would not widen the view.
        raise ValueError(
            "Cosmos cameras need an uncalibrated pinhole lens; the canvas widens the aperture, which a camera with "
            "OpenCV calibration (spawn.distortion) does not follow."
        )
    if spawn is None:
        if canvas_width * camera.height != canvas_height * camera.width:
            logger.warning("The Cosmos canvas changes this camera's aspect ratio; its view is cropped.")
        return spawn
    # Renderers use square pixels, so the vertical aperture follows the horizontal one and the image size.
    vertical = spawn.horizontal_aperture * camera.height / camera.width
    if canvas_width * vertical >= canvas_height * spawn.horizontal_aperture:
        return replace(spawn, horizontal_aperture=vertical * canvas_width / canvas_height, vertical_aperture=vertical)
    return replace(spawn, vertical_aperture=spawn.horizontal_aperture * canvas_height / canvas_width)


def _center_crop_resize(data: torch.Tensor, width: int, height: int) -> torch.Tensor:
    """Cut the camera's original view out of the canvas's center and area-resize it to the camera's size."""
    _, rows, cols, _ = data.shape
    if cols * height > rows * width:
        crop = rows * width // height
        data = data[:, :, (cols - crop) // 2 : (cols - crop) // 2 + crop]
    else:
        crop = cols * height // width
        data = data[:, (rows - crop) // 2 : (rows - crop) // 2 + crop]
    pixels = torch.nn.functional.interpolate(data.permute(0, 3, 1, 2).float(), size=(height, width), mode="area")
    return pixels.round().clamp(0, 255).to(torch.uint8).permute(0, 2, 3, 1).contiguous()
