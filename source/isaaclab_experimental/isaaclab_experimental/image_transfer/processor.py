"""Image generation from per-view control sequences, applied as camera tensor processors."""

from __future__ import annotations

import math
from collections.abc import Sequence
from typing import TYPE_CHECKING

import torch
import warp as wp

from isaaclab.sensors.camera import CAPTURE_ENV_MASK_NAME
from isaaclab.sim import SimulationContext
from isaaclab.utils import instantiate, string_to_callable
from isaaclab.utils.tensor_processors import TensorProcessor
from isaaclab.utils.warp import ProxyArray

if TYPE_CHECKING:
    from .backend import ImageTransferModel
    from .processor_cfg import FunctionProcessorCfg, ImageTransferProcessorCfg

_SEED_MODULUS = 2**31


class ImageTransferProcessor(TensorProcessor):
    """Queue uint8 controls per view and publish images generated by an application-owned model.

    Each call queues one control for every view in the ``env_mask`` input, or for every view without one. With
    ``update_period > 0``, environments that reset independently capture at different steps, so a capture can
    cover only some views; the others keep their last render, which is not a new frame. Views advance together:
    when every view starts an episode, the stream generates once each has ``initial_frames``; otherwise it
    generates once every continuing view has ``update_frames``. A view that reset meanwhile starts its new episode
    with its newest ``initial_frames`` and drops its older queued controls, so all views keep one chunk cadence.
    The output takes each view's last generated image and holds it until the next chunk; a reset view shows black
    until its episode starts.

    A stream error or invalid result marks the processor as failed: the stream may already have advanced,
    so it is never retried against the same queues. Recreate the camera or processor instead.
    """

    def __init__(self, cfg: ImageTransferProcessorCfg, data: dict[str, ProxyArray]):
        """Open a generation stream for the views of the control input.

        Args:
            cfg: Processor configuration. Its first input names the controls and its only output the images.
            data: Named input buffers; the controls have shape ``(N, H, W, 3)``.

        Raises:
            ValueError: If the control shape or the chunk settings are invalid.
        """
        super().__init__(cfg)
        controls = data[cfg.inputs[0]]
        data_dim = tuple(controls.shape)
        _validate(cfg, data_dim)
        self._data_dim = data_dim
        num_views = data_dim[0]
        sim = SimulationContext.instance()
        # The simulation owns shared models; a model built without one belongs to this processor.
        self._owned_model: ImageTransferModel | None = None
        if sim is not None:
            model = sim.get_or_create_backend(cfg.backend)
        else:
            model = self._owned_model = instantiate(cfg.backend)
        self._seeds = tuple((cfg.seed + row) % _SEED_MODULUS for row in range(num_views))
        self._stream = model.open_stream(num_views, self._seeds)
        self._pending: list[list[torch.Tensor]] = [[] for _ in range(num_views)]
        self._fresh = [True] * num_views
        self._episodes = [0] * num_views
        self._reset_rows: set[int] = set()
        self._started = False
        self._failed = False
        self._closed = False
        output = wp.zeros(data_dim, dtype=wp.uint8, device=controls.device)
        self._outputs = {cfg.outputs[0]: ProxyArray(output)}
        self._output = self._outputs[cfg.outputs[0]].torch

    def __call__(self, data: dict[str, ProxyArray]) -> dict[str, ProxyArray]:
        """Queue one control per captured view and generate a chunk when every view has one.

        Args:
            data: Named input buffers: the controls of shape ``(N, H, W, 3)``, dtype uint8, and optionally
                ``env_mask``.

        Returns:
            The latest generated images, shape ``(N, H, W, 3)``, under the output name. The buffer is reused by
            later calls.

        Raises:
            RuntimeError: If the processor is closed or failed, or a view's queue is full.
            ValueError: If the controls or the generated images have the wrong shape or type.
        """
        if self._closed or self._failed:
            raise RuntimeError("Image transfer processor is closed or failed; recreate it.")
        cfg = self._cfg
        frames = data[cfg.inputs[0]].torch
        if tuple(frames.shape) != self._data_dim or frames.dtype != torch.uint8:
            raise ValueError(f"Image transfer controls must be uint8 with shape {self._data_dim}.")
        mask = data.get(CAPTURE_ENV_MASK_NAME)
        captured = mask.torch.tolist() if mask is not None else [True] * len(self._pending)
        # Only views that capture now add a control; a full view that skips this capture does not block the others.
        if any(captured[row] and len(queue) >= cfg.max_pending_frames for row, queue in enumerate(self._pending)):
            raise RuntimeError("Image transfer control queue is full; views must reset and advance compatibly.")
        with torch.no_grad():
            for row, queue in enumerate(self._pending):
                if captured[row]:
                    queue.append(frames[row].clone())
            counts = [cfg.initial_frames if fresh else cfg.update_frames for fresh in self._fresh]
            if not all(len(queue) >= count for queue, count in zip(self._pending, counts)):
                return dict(self._outputs)
            # A view starting while others continue joins at the next chunk with its newest controls.
            controls = [
                torch.stack(queue[-count:] if fresh else queue[:count])
                for queue, count, fresh in zip(self._pending, counts, self._fresh)
            ]
            resets = tuple(sorted(self._reset_rows)) if self._started else ()
            num_views = len(self._pending)
            seeds = tuple((self._seeds[row] + self._episodes[row] * num_views) % _SEED_MODULUS for row in resets)
            try:
                generated = self._stream.step(controls, resets, seeds)
                if len(generated) != num_views:
                    raise ValueError("Image transfer returned the wrong number of views.")
                for images, count in zip(generated, counts):
                    if tuple(images.shape) != (count, *self._data_dim[1:]) or images.dtype != torch.uint8:
                        raise ValueError("Image transfer must return uint8 THWC RGB matching each control chunk.")
            except Exception:
                self._failed = True
                raise
            # Publish only after the whole result is validated.
            for row, (images, count) in enumerate(zip(generated, counts)):
                self._output[row].copy_(images[-1])
                if self._fresh[row]:
                    self._pending[row].clear()
                else:
                    del self._pending[row][:count]
                self._fresh[row] = False
            self._started = True
            self._reset_rows.clear()
        return dict(self._outputs)

    def reset(self, env_ids: Sequence[int] | torch.Tensor | None = None):
        """Discard the queued controls and episode state of the selected views.

        Args:
            env_ids: Views to reset. Defaults to None, which resets all views.
        """
        if self._closed:
            return
        if env_ids is None:
            rows = range(len(self._pending))
        else:
            rows = env_ids.tolist() if isinstance(env_ids, torch.Tensor) else list(env_ids)
        for row in rows:
            self._pending[row].clear()
            self._fresh[row] = True
            # A reset before the first generation has no episode to discard.
            if self._started:
                self._episodes[row] += 1
                self._reset_rows.add(row)
            self._output[row].zero_()

    def close(self) -> None:
        """Close the stream and, without a simulation context, the model."""
        if self._closed:
            return
        self._closed = True
        self._pending = [[] for _ in self._pending]
        try:
            self._stream.close()
        finally:
            if self._owned_model is not None:
                self._owned_model.close()


class FunctionProcessor(TensorProcessor):
    """Apply a Torch function to one camera buffer and publish the result in a persistent buffer.

    The function takes the input tensor and :attr:`TensorProcessorCfg.params` as keyword arguments, and returns a
    tensor whose shape and dtype do not change between calls, for example :func:`depth_to_control`.
    """

    def __init__(self, cfg: FunctionProcessorCfg, data: dict[str, ProxyArray]):
        """Allocate the output from the function's result on a zero input of the input's shape.

        Args:
            cfg: Processor configuration with one input and one output.
            data: Named input buffers.
        """
        super().__init__(cfg)
        function = cfg.function
        self._function = string_to_callable(function) if isinstance(function, str) else function
        source = data[cfg.inputs[0]].torch
        with torch.no_grad():
            sample = self._function(torch.zeros_like(source), **cfg.params)
        output = wp.zeros(tuple(sample.shape), dtype=wp.dtype_from_torch(sample.dtype), device=str(source.device))
        self._outputs = {cfg.outputs[0]: ProxyArray(output)}
        self._output = self._outputs[cfg.outputs[0]].torch

    def __call__(self, data: dict[str, ProxyArray]) -> dict[str, ProxyArray]:
        """Apply the function to the input and copy the result into the output buffer."""
        with torch.no_grad():
            self._output.copy_(self._function(data[self._cfg.inputs[0]].torch, **self._cfg.params))
        return dict(self._outputs)


def depth_to_control(data: torch.Tensor, near: float = 0.1, far: float = 10.0) -> torch.Tensor:
    """Map metric depth to uint8 three-channel controls.

    Hits at ``near`` become white and hits at ``far`` black. Missing, nonfinite, and nonpositive
    depth becomes black.

    Args:
        data: Depth [m] of shape ``(N, H, W, 1)``.
        near: White depth endpoint [m].
        far: Black depth endpoint [m].

    Returns:
        Controls of shape ``(N, H, W, 3)``, dtype uint8.
    """
    if not (math.isfinite(near) and math.isfinite(far) and 0 < near < far):
        raise ValueError("Depth bounds must be finite and satisfy 0 < near < far.")
    valid = torch.isfinite(data) & (data > 0)
    metric = torch.where(valid, data, far)
    pixels = ((far - metric) / (far - near)).clamp(0, 1).mul(255).round().to(torch.uint8)
    return pixels.expand(*pixels.shape[:-1], 3)


def _validate(cfg: ImageTransferProcessorCfg, data_dim: tuple[int, ...]) -> None:
    if len(data_dim) != 4 or data_dim[-1] != 3:
        raise ValueError(f"Image transfer expects controls with shape (N, H, W, 3), got {data_dim}.")
    sizes = (cfg.initial_frames, cfg.update_frames, cfg.max_pending_frames)
    if any(type(value) is not int or value < 1 for value in sizes):
        raise ValueError("Chunk sizes and queue capacity must be positive integers.")
    if cfg.max_pending_frames < max(cfg.initial_frames, cfg.update_frames):
        raise ValueError("Queue capacity must accommodate both configured chunk sizes.")
